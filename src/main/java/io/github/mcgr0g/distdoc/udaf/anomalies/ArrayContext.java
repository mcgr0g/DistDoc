package io.github.mcgr0g.distdoc.udaf.anomalies;

import java.util.List;

/**
 * Неизменяемый контейнер данных (Data Transfer Object), инкапсулирующий состояние конкретного
 * JSON-массива, собранное в процессе потокового сканирования документа.
 *
 * <p>Объект создается в момент обработки токена {@code END_ARRAY} и передается в
 * конвейер детекции аномалий {@link ArrayAnomalyDetector}. Служит для изоляции
 * сырых данных от мутабельного хранилища метрик.</p>
 *
 * @param path        Абсолютный путь к элементам массива в формате JSONPath (например, {@code "$.user.orders[*]"}).
 *                    Используется как уникальный ключ при агрегации и маппинге результатов для dbt.
 * @param elements    Упорядоченный список строковых представлений всех элементов, физически
 *                    прочитанных из текущего массива. Для примитивов содержит текстовый эквивалент
 *                    значения (например, {@code "1995"}), для объектов и вложенных массивов — пустые строки
 *                    или маркеры структуры, так как их вложенные свойства анализируются изолированно.
 * @param totalElements Число всех элементов массива любого типа (скаляры, объекты, вложенные массивы, {@code null}).
 *                    Единственный критерий пустоты массива: список {@code elements} содержит только скалярные литералы,
 *                    поэтому массив объектов имеет пустой {@code elements}, но не пуст.
 * @param allStrings  Флаг однородности строкового типа. Принимает значение {@code true} только в том случае,
 *                    если <b>все</b> встреченные элементы массива имели тип {@code VALUE_STRING}.
 *                    Используется для выявления плоских текстовых списков.
 * @param allNumbers  Флаг однородности числового типа. Принимает значение {@code true} только в том случае,
 *                    если <b>все</b> встреченные элементы массива имели тип {@code VALUE_NUMBER_INT}.
 *                    Используется для точечной валидации списков идентификаторов или временных компонентов.
 *
 * @see ArrayAnomalyDetector
 * @see io.github.mcgr0g.distdoc.udaf.PathMetrics
 */
public record ArrayContext(
        String path,
        List<String> elements,
        int totalElements,
        boolean allStrings,
        boolean allNumbers
) {}
