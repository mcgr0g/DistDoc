package io.github.mcgr0g.distdoc.udaf.anomalies;

import io.github.mcgr0g.distdoc.udaf.PathMetrics;

/**
 * Интерфейс стратегии (Pattern Strategy) для детекции структурных аномалий в массивах.
 * <p>
 * Служит для изоляции бизнес-логики валидации данных (специфичной для dbt/DWH слоя)
 * от базового ядра стримингового парсера {@link io.github.mcgr0g.distdoc.udaf.JsonSchemaAnalyzer}.
 * </p>
 *
 * <p><b>Принцип расширения:</b></p>
 * Если для генерации dbt staging-моделей требуется выявить новую аномалию в массиве
 * (например, смешение типов данных или слишком глубокую вложенность), необходимо
 * создать новую реализацию данного интерфейса и зарегистрировать её в анализаторе,
 * не изменяя код самого Jackson-парсера.
 *
 * <p><b>Требования к реализации:</b></p>
 * <ul>
 *   <li>Реализации должны быть <b>без состояния (stateless)</b>, так как один и тот же
 *       экземпляр детектора вызывается последовательно для миллионов строк на воркере.</li>
 *   <li>Все имена записываемых аномалий должны соответствовать конвенции именования Trino SQL
 *       (нижний регистр, стиль {@code snake_case}, префикс {@code is_} или {@code has_}).</li>
 * </ul>
 *
 * @see ArrayContext
 * @see PathMetrics
 * @see AnomalyDetector
 */
@FunctionalInterface
public interface ArrayAnomalyDetector {

    /**
     * Анализирует накопленный контекст элементов конкретного массива и обогащает
     * объект метрик выявленными флагами аномалий.
     *
     * @param context неизменяемый snapshot данных (DTO), содержащий абсолютный jsonpath
     *                массива, список строковых представлений его элементов и флаги однородности типов
     * @param metrics мутабельный контейнер метрик текущего пути, в карту аномалий которого
     *                записываются результаты анализа (через {@link PathMetrics#setAnomaly(String, boolean)})
     */
    void detect(ArrayContext context, PathMetrics metrics);
}
